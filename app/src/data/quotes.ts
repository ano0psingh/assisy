// Get a deterministic quote based on the date
export function getQuoteOfTheDay(): { text: string; author: string } {
  const today = new Date();
  const startOfYear = new Date(today.getFullYear(), 0, 0);
  const diff = today.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  
  // Use day of year to pick a quote (cycles through all quotes over the year)
  const index = dayOfYear % quotes.length;
  return quotes[index];
}

// Get the last shown date from localStorage
const QUOTE_LAST_SHOWN_KEY = 'life-rpg-quote-last-shown';

export function shouldShowQuote(): boolean {
  const lastShown = localStorage.getItem(QUOTE_LAST_SHOWN_KEY);
  const today = new Date().toDateString();
  return lastShown !== today;
}

export function markQuoteAsShown(): void {
  localStorage.setItem(QUOTE_LAST_SHOWN_KEY, new Date().toDateString());
}
